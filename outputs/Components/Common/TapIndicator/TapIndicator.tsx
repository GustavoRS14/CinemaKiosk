import React, { useLayoutEffect, useRef } from 'react';
import TouchIcon from '@icons/touch.svg';
import './TapIndicator.css';

export interface TapIndicatorProps {
/* The text displayed below the icon */
label?: string;
/* Optional click handler */
onClick?: () => void;
className?: string;
}

export const TapIndicator: React.FC<TapIndicatorProps> = ({
label = 'TOQUE NA TELA',
onClick,
className = '',
}) => {
const wrapperClass = `tap-indicator ${className}`.trim();
const containerRef = useRef<HTMLDivElement>(null);
const textRef = useRef<HTMLSpanElement>(null);

// useLayoutEffect runs synchronously before the browser paints,
// ensuring the user never sees the text flash at the wrong size.
useLayoutEffect(() => {
  const container = containerRef.current;
  const textEl = textRef.current;
  if (!container || !textEl) return;

  // 1. Clear any inline styles to let the pure CSS tokens apply
  textEl.style.fontSize = '';
  textEl.style.lineHeight = '';

  // 2. Dynamically read the actual pixel size generated by the CSS token
  const computedStyle = window.getComputedStyle(textEl);
  let currentSize = parseFloat(computedStyle.fontSize); // e.g., parses "20px" to 20

  // Fallback just in case getComputedStyle fails (updated to H6 base size)
  if (isNaN(currentSize)) currentSize = 20;

  // 3. Loop: If the internal content exceeds the fixed 144px height, shrink it iteratively
  // Min size lowered to 10 to allow wrapping in the smaller container
  while (container.scrollHeight > container.clientHeight && currentSize > 10) {
    currentSize -= 1;
    // Inline styles override the CSS token ONLY when scaling down is required
    textEl.style.fontSize = `${currentSize}px`;
    // Maintain the 1.2 line-height proportion from the original design (24/20 = 1.2)
    textEl.style.lineHeight = `${Math.round(currentSize * 1.2)}px`;
  }
}, [label]);

return (
  <div
    ref={containerRef}
    className={wrapperClass}
    onClick={onClick}
    role="button"
    tabIndex={0}
    aria-label={label}
  >
    <TouchIcon className="tap-indicator__icon"/>
    <span ref={textRef} className="tap-indicator__label">{label}</span>
  </div>
);
};
